//to print * (3 rows and 3columns) using nested for loop
import java.util.Scanner;
class demo
{
    public static void main(String[] args)
    {
        
        for(int i=0;i<=2;i++)
        {
            
            for(int j=0;j<=2;j++)
            {
                System.out.print("*");
            }
           System.out.println();
        }
    
    
}
}
      




